// CountryOfICAO24 returns the state of registry for a lower case hex address, or empty when unallocated.
func CountryOfICAO24(hex string) string {
	n, err := strconv.ParseUint(hex, 16, 32)
	if err != nil {
		return ""
	}
	addr := uint32(n)
	country, span := "", uint32(0)
	for _, b := range icaoBlocks {
		if b.from > addr {
			break
		}
		if addr <= b.to && (country == "" || b.to-b.from < span) {
			country, span = b.country, b.to-b.from
		}
	}
	return country
}
